// The Finances → Reports PDF, as data. Pure: the component hands it what it
// already computed for the screen (summary, monthly series, categories, aging)
// and gets back a document model — title, KPI row, tables — that the client
// renderer (`core/app/utils/report-pdf.ts`, jsPDF lazily imported) draws.
// Keeping the shape here means the PDF's numbers are unit-tested and are the
// same numbers the screen and the CSVs show.

import type { CategoryTotal, DelinquencyReport, LedgerSummary, MonthlyBucket } from "./ledger";

export interface ReportTable {
  title: string;
  head: string[];
  body: string[][];
  /** A totals row, drawn bold. */
  foot?: string[];
  /** Column indexes that are money (right-aligned). */
  numeric: number[];
  /** Shown instead of an empty table. */
  emptyText: string;
}

export interface ReportDoc {
  title: string;
  subtitle: string;
  kpis: Array<{ label: string; value: string }>;
  tables: ReportTable[];
  footer: string;
  filename: string;
}

export interface ReportDocInput {
  orgName?: string | null;
  rangeLabel: string;
  generatedAt: string;
  summary: LedgerSummary;
  hasOpening: boolean;
  series: MonthlyBucket[];
  incomeCats: CategoryTotal[];
  expenseCats: CategoryTotal[];
  aging: DelinquencyReport;
  currency: (v?: number | null) => string;
  monthLabel: (key: string) => string;
  catLabel: (c: string) => string;
  fdate: (d?: string | null) => string;
}

const pct = (share: number) => `${Math.round(share * 100)}%`;

/** A filesystem-safe slug for the download name. */
export function reportSlug(name?: string | null): string {
  const s = (name || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return s || "community";
}

export function buildFinancialReportDoc(i: ReportDocInput): ReportDoc {
  const day = i.generatedAt.slice(0, 10);
  const kpis = [
    { label: "Income", value: i.currency(i.summary.totalIncome) },
    { label: "Expenses", value: i.currency(i.summary.totalExpense) },
    { label: "Net", value: i.currency(i.summary.net) },
    ...(i.hasOpening ? [{ label: "Balance", value: i.currency(i.summary.closingBalance) }] : []),
    { label: "Outstanding", value: i.currency(i.aging.totals.outstanding) },
  ];

  const monthly: ReportTable = {
    title: `Monthly summary — ${i.rangeLabel}`,
    head: ["Month", "Income", "Expense", "Net", "Running balance"],
    body: [
      ...(i.hasOpening
        ? [["Opening balance", "", "", "", i.currency(i.summary.openingBalance)]]
        : []),
      ...i.series.map((m) => [
        i.monthLabel(m.month),
        i.currency(m.income),
        i.currency(m.expense),
        i.currency(m.net),
        i.currency(m.runningBalance),
      ]),
    ],
    foot: i.series.length
      ? [
          "Total",
          i.currency(i.series.reduce((s, m) => s + m.income, 0)),
          i.currency(i.series.reduce((s, m) => s + m.expense, 0)),
          i.currency(i.series.reduce((s, m) => s + m.net, 0)),
          i.currency(i.series[i.series.length - 1]!.runningBalance),
        ]
      : undefined,
    numeric: [1, 2, 3, 4],
    emptyText: "No financial activity in this range.",
  };

  const cats = (title: string, rows: CategoryTotal[], emptyText: string): ReportTable => ({
    title,
    head: ["Category", "Total", "Share"],
    body: rows.map((c) => [i.catLabel(c.category), i.currency(c.total), pct(c.share)]),
    numeric: [1, 2],
    emptyText,
  });

  const t = i.aging.totals;
  const aging: ReportTable = {
    title: "Delinquency aging",
    head: ["Member", "Current", "1–30", "31–60", "61–90", "90+", "Outstanding", "Oldest due"],
    body: i.aging.rows.map((r) => [
      r.memberName,
      i.currency(r.current),
      i.currency(r.d1_30),
      i.currency(r.d31_60),
      i.currency(r.d61_90),
      i.currency(r.d90_plus),
      i.currency(r.outstanding),
      i.fdate(r.oldestDueDate),
    ]),
    foot: i.aging.rows.length
      ? [
          "Total",
          i.currency(t.current),
          i.currency(t.d1_30),
          i.currency(t.d31_60),
          i.currency(t.d61_90),
          i.currency(t.d90_plus),
          i.currency(t.outstanding),
          "",
        ]
      : undefined,
    numeric: [1, 2, 3, 4, 5, 6],
    emptyText: "No outstanding balances.",
  };

  return {
    title: `${i.orgName || "Community"} — Financial report`,
    subtitle: `${i.rangeLabel} · generated ${i.fdate(i.generatedAt)}`,
    kpis,
    tables: [
      monthly,
      cats("Income by type", i.incomeCats, "No income recorded."),
      cats("Expenses by category", i.expenseCats, "No expenses recorded."),
      aging,
    ],
    footer: "Generated by HOA Connect from the community's payment records.",
    filename: `${reportSlug(i.orgName)}-financial-report-${day}.pdf`,
  };
}
